"""Generate publication tables and figures from results/<model>/tables.json.

Run from the repository root: python -m analysis.build_paper
"""
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
TABLES = HERE / "paper" / "tables"
FIGS = HERE / "paper" / "figures"
ASSET_SUFFIX = ""
os.environ.setdefault("MPLCONFIGDIR", str(HERE / "results" / "cache" / "matplotlib"))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import NullLocator

MODELS = {"qwen3-8b": "Qwen3-8B", "gpt-oss-20b": "gpt-oss-20b"}
CORPORA = {"amazon": "Amazon-20", "reddit": "Reddit"}
CELLS = [(c, s) for c in CORPORA for s in ("titles", "meta")]
DATA = {m: json.loads((HERE / "results" / m / "tables.json").read_text()) for m in MODELS}
BLUE, GREEN, ORANGE, GREY, INK = "#2475B0", "#16846B", "#D36C35", "#788393", "#424852"
CONFIGS = [
    ("no retrieval, no reasoning", "Neither", INK, "o"),
    ("arbitrary retrieval, no reasoning", "Random reviews", GREY, "v"),
    ("retrieval, no reasoning", "Selected reviews", BLUE, "o"),
    ("reasoning, no retrieval", "Reasoning only", ORANGE, "s"),
    ("retrieval and reasoning", "Selected + reasoning", GREEN, "D"),
]


def one(rows, **kw):
    matches = [r for r in rows if all(r.get(k) == v for k, v in kw.items())]
    assert len(matches) == 1, (kw, len(matches))
    return matches[0]


def number(x, signed=False):
    if abs(x) < 0.0005:
        x = 0.0
    return f"{x:+.3f}" if signed else f"{x:.3f}"


def delta(r):
    s = number(r["delta"], True)
    if r.get("holm", 1) < .05:
        s = r"\mathbf{" + s + "}"
    elif r["lo"] > 0 or r["hi"] < 0:
        s = r"\mathit{" + s + "}"
    return "$" + s + "$"


def interval(r):
    return r"\ci{" + number(r["lo"], True) + "}{" + number(r["hi"], True) + "}"


def row(values):
    return " & ".join(values) + r" \\"


def group(text, n):
    return r"\midrule\multicolumn{" + str(n) + r"}{l}{\emph{" + text + r"}} \\"


def settings_header(first):
    return row([first] + [r"\shortstack{" + CORPORA[c] + r"\\" + ("titles only" if s == "titles" else "+ metadata") + "}" for c, s in CELLS])


def table(name, spec, lines):
    text = "% Generated by analysis.build_paper from results/<model>/tables.json.\n"
    text += "\\begin{tabular}{" + spec + "}\n\\toprule\n"
    text += "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / f"{name}{ASSET_SUFFIX}.tex").write_text(text)


def tables():
    for model, title in MODELS.items():
        lines = [row(["configuration", "HR@1", "HR@10", "MRR", "NDCG@10", "prompt", "generated"])]
        for c, s in CELLS:
            rows = [r for r in DATA[model]["table1"] if (r["corpus"], r["setting"]) == (c, s)]
            assert len(rows) == 5
            lines.append(group(f"{CORPORA[c]}, " + ("titles only" if s == "titles" else "titles + metadata") + f" ($n={rows[0]['n']}$)", 7))
            for config, label, *_ in CONFIGS:
                r = one(rows, config=config)
                lines.append(row([label] + [f"${r[k]:.3f}$" for k in ("hr1", "hr10", "mrr", "ndcg10")]
                                 + ["$" + f"{r[k]:,.0f}".replace(",", "{,}") + "$" for k in ("prompt", "generated")]))
        table("tab_design" + ("_oss" if model == "gpt-oss-20b" else ""), "lrrrrrr", lines)

    contrasts = [
        ("retrieval, no reasoning - neither", "Selected $-$ neither"),
        ("against arbitrary retrieval", "Selected $-$ random"),
        ("retrieval and reasoning - reasoning only", "Both $-$ reasoning"),
        ("reasoning, no retrieval - neither", "Reasoning $-$ neither"),
        ("retrieval and reasoning - retrieval only", "Both $-$ selected"),
        ("retrieval only - reasoning only", "Selected $-$ reasoning"),
    ]
    lines = [settings_header("contrast")]
    for model, title in MODELS.items():
        lines.append(group(title, 5))
        for key, label in contrasts:
            rs = [one(DATA[model]["table8"], corpus=c, setting=s, contrast=key) for c, s in CELLS]
            lines += [row([label] + [delta(r) for r in rs]), row([""] + [interval(r) for r in rs])]
    table("tab_contrasts", "lcccc", lines)

    four = [(m, c) for m in MODELS for c in CORPORA]
    header = [r"\shortstack{" + MODELS[m] + r"\\" + CORPORA[c] + "}" for m, c in four]
    lines = [row(["contrast (titles only)"] + header)]
    for key in ("retrieved - arbitrary", "arbitrary - none", "retrieved - none", "re-filed - none", "retrieved - re-filed"):
        rs = [one(DATA[m]["table7"], corpus=c, setting="titles", contrast=key) for m, c in four]
        lines += [row([key.replace(" - ", " $-$ ")] + [delta(r) for r in rs]), row([""] + [interval(r) for r in rs])]
    table("tab_attribution", "lcccc", lines)

    lines = [row(["review-block content"] + header)]
    labels = {"real": "Own review", "swap": "Swapped review", "filler": "Matched filler", "template": "Template only", "real - swap": "Own $-$ swapped"}
    for shown, name in (("top", "Reader's top three"), ("rand", "Three at random")):
        lines.append(group(name, 5))
        for key, label in labels.items():
            rs = [one(DATA[m]["table6"], corpus=c, shown_set=shown, mode="reviews", content=key) for m, c in four]
            lines += [row([label] + [f"${r['delta']:+.3f}$" for r in rs]), row([""] + [interval(r) for r in rs])]
    table("tab_avail", "lcccc", lines)

    lines = [settings_header("$K$, rule / component")]
    for model, title in MODELS.items():
        lines.append(group(title, 5))
        for K in (3, 10):
            rs = [one(DATA[model]["table3"], corpus=c, setting=s, K=K, rule="relevance", term="total") for c, s in CELLS]
            lines.append(row([f"$K={K}$; $n$"] + [str(r["n"]) for r in rs]))
            for rule in ("relevance", "contrastive"):
                for term in ("total", "allocation", "content"):
                    rs = [one(DATA[model]["table3"], corpus=c, setting=s, K=K, rule=rule, term=term) for c, s in CELLS]
                    lines.append(row([(rule + ", total") if term == "total" else r"\quad " + term] + [delta(r) for r in rs]))
            lines.append(r"\addlinespace")
    table("tab_shufdeep", "lrrrr", lines)

    lines = [settings_header("$K$, allocation")]
    for model, title in MODELS.items():
        lines.append(group(title, 5))
        for K in (3, 10):
            for arm, label in (("relevance-one_each", "one each"), ("relevance-shared", "shared"), ("leader", "leader"), ("softmax", "softmax"), ("inverse", "inverse")):
                rs = [one(DATA[model]["table4"], corpus=c, setting=s, K=K, arm=arm) for c, s in CELLS]
                lines.append(row([f"{K}, {label}"] + [delta(r) for r in rs]))
            lines.append(r"\addlinespace")
    table("tab_allocdesign", "lrrrr", lines)

    columns = [(c, s, K) for c, s in CELLS for K in (3, 10)]
    lines = [row(["rule"] + [r"\multicolumn{2}{c}{" + CORPORA[c] + (", titles" if s == "titles" else ", + meta") + "}" for c, s in CELLS]),
             row([""] + ["$K=3$", "$K=10$"] * 4)]
    for model, title in MODELS.items():
        lines.append(group(title, 9))
        rs = [one(DATA[model]["table5"], corpus=c, setting=s, K=K, arm="relevance-one_each") for c, s, K in columns]
        lines += [row(["$n$"] + [str(r["n"]) for r in rs]), row(["recall@$K$"] + [f"${r['recall']:.3f}$" for r in rs])]
        for allocation, name in (("one_each", "One passage each"), ("shared", "Shared budget")):
            lines.append(group(name + ", minus presence-matched", 9))
            for objective in ("relevance", "contrastive", "mmr", "dpp"):
                rs = [one(DATA[model]["table5"], corpus=c, setting=s, K=K, arm=f"{objective}-{allocation}") for c, s, K in columns]
                lines.append(row([{"mmr": "MMR", "dpp": "determinantal"}.get(objective, objective)] + [delta(r) for r in rs]))
        rs = [one(DATA[model]["table5"], corpus=c, setting=s, K=K, arm="presence - none") for c, s, K in columns]
        lines.append(row(["Presence $-$ none"] + [delta(r) for r in rs]))
    table("tab_rules", "lrrrrrrrr", lines)

    lines = [row(["allocation / rule"] + [r"\multicolumn{2}{c}{" + CORPORA[c] + (", titles" if s == "titles" else ", + meta") + "}" for c, s in CELLS]),
             row([""] + ["HR@1", "$\\Delta$"] * 4)]
    for model, title in MODELS.items():
        lines.append(group(title, 9))
        for arm, label in (("none", "No evidence (0)"), ("v-presence", "Random, one each (20)"), ("v-relevance-each", "Relevance, one each (20)"),
                           ("v-relevance-shared20", "Shared: relevance"), ("v-contrastive-shared20", "Shared: contrastive"),
                           ("v-dpp-shared20", "Shared: determinantal"), ("v-mmr-shared20", "Shared: MMR")):
            vals = [label]
            for c, s in CELLS:
                r = one(DATA[model]["table10"], corpus=c, setting=s, arm=arm)
                vals += [f"${r['hr1']:.3f}$", delta(r) if "delta" in r else "---"]
            lines.append(row(vals))
    table("tab_k20", "lrrrrrrrr", lines)

    lines = [row(["corpus / prompt", "$B$", "With placeholder", "Placeholder omitted"])]
    for c, s in CELLS:
        for B in (3, 5, 10):
            a = one(DATA["qwen3-8b"]["budgets"], corpus=c, setting=s, B=B, contrast="arbitrary - none")
            b = one(DATA["qwen3-8b"]["omit"], corpus=c, setting=s, arm=f"arbitrary-{B} - none, line omitted")
            label = CORPORA[c] + (", titles" if s == "titles" else ", + metadata")
            lines.append(row([label if B == 3 else "", str(B), delta(a) + " " + interval(a), delta(b) + " " + interval(b)]))
    table("tab_placeholder", "lrcc", lines)


def save(fig, name):
    FIGS.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(FIGS / f"{name}{ASSET_SUFFIX}.{ext}", dpi=240, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def panel(ax, title):
    ax.set_title(title, fontsize=9, loc="left", pad=8, fontweight="bold")
    ax.grid(axis="y", color="#DFE3E8", linewidth=.55)
    ax.set_axisbelow(True)
    ax.tick_params(length=3, width=.6)


def figures():
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8, "axes.labelsize": 8,
        "axes.spines.top": False, "axes.spines.right": False, "axes.edgecolor": "#B9C0C8",
        "axes.linewidth": .6, "text.color": INK, "axes.labelcolor": INK, "xtick.color": INK,
        "ytick.color": INK, "legend.frameon": False, "pdf.fonttype": 42, "ps.fonttype": 42})
    fig, axes = plt.subplots(2, 2, figsize=(6.8, 4.55), sharey=True)


    cost_labels = {
        ("qwen3-8b", "amazon"): [(.29, .39), (.54, .10), (.53, .67), (.88, .12), (.84, .78)],
        ("qwen3-8b", "reddit"): [(.20, .33), (.25, .09), (.44, .65), (.74, .43), (.84, .83)],
        ("gpt-oss-20b", "amazon"): [(.25, .48), (.54, .23), (.53, .76), (.88, .14), (.84, .80)],
        ("gpt-oss-20b", "reddit"): [(.16, .38), (.42, .70), (.23, .90), (.72, .44), (.88, .74)],
    }
    for i, (model, title) in enumerate(MODELS.items()):
        for j, (corpus, name) in enumerate(CORPORA.items()):
            ax = axes[i, j]
            panel(ax, f"{title} · {name}")
            for k, (config, label, color, marker) in enumerate(CONFIGS):
                r = one(DATA[model]["table1"], corpus=corpus, setting="titles", config=config)
                xy = (r["prompt"] + r["generated"], r["hr1"])
                ax.plot(*xy, marker=marker, color=color,
                        ms=6.2, mec="white", mew=.65, linestyle="none", zorder=4)
                label = (label.replace("Selected + reasoning", "Selected +\nreasoning")
                              .replace(" reviews", "\nreviews").replace("Reasoning only", "Reasoning\nonly"))
                ax.annotate(label, xy, xytext=cost_labels[model, corpus][k], textcoords="axes fraction",
                            ha="center", va="center", fontsize=7.4, color=color, linespacing=1.05,
                            arrowprops=dict(arrowstyle="-", color=color, lw=.55, alpha=.65, shrinkA=2, shrinkB=5),
                            bbox=dict(facecolor="white", edgecolor="none", alpha=.9, pad=.8),
                            zorder=5)
                if config == CONFIGS[0][0]:
                    ax.axhline(r["hr1"], ls=(0, (3, 3)), lw=.9, color=INK, alpha=.65)
            ax.set(xscale="log", xlim=(450, 6500), ylim=(.23, .48), xticks=[500, 1000, 2000, 4000],
                   xticklabels=["500", "1,000", "2,000", "4,000"])
            ax.xaxis.set_minor_locator(NullLocator())
            if i == 1:
                ax.set_xlabel("Tokens / query (prompt + generated; log scale)")
            if j == 0:
                ax.set_ylabel("HR@1")
    fig.subplots_adjust(left=.09, right=.99, top=.93, bottom=.12, wspace=.14, hspace=.37)
    save(fig, "fig_levers")

    fig, axes = plt.subplots(2, 2, figsize=(6.8, 4.8), sharey=True)
    for i, (model, title) in enumerate(MODELS.items()):
        for j, (corpus, name) in enumerate(CORPORA.items()):
            ax = axes[i, j]
            panel(ax, f"{title} · {name}")
            for arm, think, color, marker in (("contrastive", False, BLUE, "o"), ("contrastive", True, GREEN, "D"), ("count", False, GREY, "v")):
                rs = sorted([r for r in DATA[model]["budgets"] if r["corpus"] == corpus and r["setting"] == "titles"
                             and r.get("arm") == arm and r.get("think") == think], key=lambda r: r["B"])
                assert [r["B"] for r in rs] == [3, 5, 10, 20, 40]
                x, y = [r["B"] for r in rs], [r["hr1"] for r in rs]
                ax.plot(x, y, marker=marker, color=color, lw=1.5, ms=4.8, mec="white", mew=.55, zorder=4)
                if arm == "count":

                    ax.fill_between(x, [r["lo"] for r in rs], [r["hi"] for r in rs],
                                    color=GREY, alpha=.16, linewidth=0, zorder=1)
            for config, color, ls in (("no retrieval, no reasoning", INK, (0, (1, 2))), ("reasoning, no retrieval", ORANGE, (0, (4, 3)))):
                r = one(DATA[model]["table1"], corpus=corpus, setting="titles", config=config)
                ax.axhline(r["hr1"], color=color, ls=ls, lw=1, alpha=.85)
            ax.set(xscale="log", xlim=(2.5, 47), ylim=(.22, .49), xticks=[3, 5, 10, 20, 40], xticklabels=["3", "5", "10", "20", "40"])
            ax.xaxis.set_minor_locator(NullLocator())
            if i == 1:
                ax.set_xlabel("Review budget (log scale)")
            if j == 0:
                ax.set_ylabel("HR@1")
    handles = [Line2D([], [], color=BLUE, marker="o", ms=4, label="Selected reviews"),
               Line2D([], [], color=GREEN, marker="D", ms=4, label="Selected + reasoning"),
               Line2D([], [], color=GREY, marker="v", ms=4, label="Random reviews (95% CI)"),
               Line2D([], [], color=INK, ls=":", label="Neither"),
               Line2D([], [], color=ORANGE, ls="--", label="Reasoning only")]
    fig.legend(handles=handles, loc="lower center", ncol=3, fontsize=7.7, columnspacing=1.7)
    fig.subplots_adjust(left=.09, right=.99, top=.93, bottom=.19, wspace=.14, hspace=.37)
    save(fig, "fig_budget")
    availability_figure("top", "fig_availability")
    availability_figure("rand", "fig_availability_sets")


def availability_figure(shown, filename):
    fig, axes = plt.subplots(2, 2, figsize=(6.8, 4.35))
    styles = [("real", "Own reviews", BLUE, "o"), ("swap", "Swapped reviews", ORANGE, "s"),
              ("filler", "Matched filler", GREY, "D"), ("template", "Template only", "#AFB6C0", "v")]
    for i, (model, title) in enumerate(MODELS.items()):
        for j, (corpus, name) in enumerate(CORPORA.items()):
            ax = axes[i, j]
            panel(ax, f"{title} · {name}")
            ax.grid(False)
            ax.grid(axis="x", color="#E4E7EB", linewidth=.55)
            base = one(DATA[model]["rates"], corpus=corpus, shown_set=shown, mode="reviews", content="none")
            ax.axvline(100 * base["rate"], color=INK, ls=(0, (3, 3)), lw=.9, zorder=1)
            for y, (content, label, color, marker) in enumerate(styles):
                r = one(DATA[model]["rates"], corpus=corpus, shown_set=shown, mode="reviews", content=content)
                ax.errorbar(100 * r["rate"], y, xerr=[[100 * (r["rate"] - r["lo"])], [100 * (r["hi"] - r["rate"])]],
                            fmt=marker, color=color, ms=5.5, mec="white", mew=.5, elinewidth=.9, capsize=2.3, capthick=.9, zorder=3)
                ax.text(100 * r["hi"] + .65, y, f"{100 * r['rate']:.1f}", va="center", fontsize=7.2, color=color)
            ax.set(yticks=range(4), yticklabels=[s[1] for s in styles], ylim=(3.65, -.6),
                   xlim=(58, 97) if shown == "top" else (0, 43))
            ax.tick_params(axis="y", length=0)
            ax.spines["left"].set_visible(False)
            ax.text(.98, .04, f"No evidence: {100 * base['rate']:.1f}%", transform=ax.transAxes, ha="right", fontsize=6.9,
                    bbox=dict(facecolor="white", edgecolor="none", pad=.6))
            if i == 1:
                ax.set_xlabel("Shown set ranked first (%)")
    fig.subplots_adjust(left=.16, right=.98, top=.93, bottom=.12, wspace=.72, hspace=.42)
    save(fig, filename)


if __name__ == "__main__":
    tables()
    figures()
    print("Built 10 result tables and four PDF/PNG figures from audited snapshots.")
